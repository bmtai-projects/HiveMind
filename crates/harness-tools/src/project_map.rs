    #[tokio::test]
    async fn a_nonexistent_path_says_so_instead_of_reporting_an_empty_map() {
        // "no files found" for a typo'd path sends the model hunting for a
        // content problem that doesn't exist.
        // A path whose parent exists but whose leaf does not -- exactly the
        // `src/crates` typo shape. (A path whose *parent* is also missing
        // is rejected earlier, by Workspace::resolve.)
        let w = ws("missing_dir");
        let err = ProjectMap(w.clone())
            .execute(&args(serde_json::json!({"path": "nope"})))
            .await
            .unwrap_err();
        assert!(err.to_string().contains("not a directory"), "{err}");

        // Pointing it at a file rather than a directory is the same class
        // of mistake and gets the same clear answer.
        std::fs::write(w.root.join("a.rs"), "pub fn x() {}\n").unwrap();
        let err = ProjectMap(w.clone())
            .execute(&args(serde_json::json!({"path": "a.rs"})))
            .await
            .unwrap_err();
        assert!(err.to_string().contains("not a directory"), "{err}");
    }

