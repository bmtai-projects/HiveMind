//! `project_map` — the structural overview a codebase-understanding task
//! should start from, instead of reading every file.
//!
//! # Why this exists
//!
//! Orienting in an unfamiliar repo used to cost a `list_dir` per directory
//! (non-recursive) plus a whole-file `read_file` per file, because there was
//! no way to learn what a file *contains* without reading all of it. On this
//! very repo that's ~20 directory calls and ~108k tokens of file content —
//! more than a 128k context window has to spare before the model has written
//! a word, and re-sent on every subsequent turn.
//!
//! One call here returns the tree plus each file's top-level definitions with
//! line numbers, for a small fraction of that. The intended workflow is
//! **map, then read precisely**: outline the repo, then `read_file` only the
//! handful of files that actually matter.
//!
//! # Why a line scanner and not tree-sitter
//!
//! Real parsers (grok-build uses tree-sitter with per-language query
//! grammars) give exact symbol extraction and go-to-definition. They also
//! mean a C grammar crate per language — and this binary cross-compiles to
//! five platform targets, where a C toolchain per target is a real ongoing
//! cost for what is, here, a *navigation hint*.
//!
//! So this scans lines with per-language rules. The tradeoff is explicit: it
//! can miss an unusually-formatted definition, and it will never see symbols
//! generated by macros. It fails in the harmless direction — a missed symbol
//! is simply absent, never a wrong file path or a build break — and every
//! line number it prints is real, because it comes from counting actual
//! lines rather than inferring position.

