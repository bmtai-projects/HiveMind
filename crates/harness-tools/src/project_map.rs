    #[tokio::test]
    async fn maps_a_tree_with_real_line_numbers() {
        let w = ws("e2e");
        std::fs::create_dir_all(w.root.join("src")).unwrap();
        std::fs::write(
            w.root.join("src/lib.rs"),
            "// header\n\npub struct Engine {\n    field: u8,\n}\n\nimpl Engine {\n    pub fn start(&self) {}\n}\n",
        )
        .unwrap();
        std::fs::write(w.root.join("README.md"), "# docs\nsome prose\n").unwrap();

        let out = ProjectMap(w.clone())
            .execute(&args(serde_json::json!({})))
            .await
            .unwrap();

        assert!(out.contains("lib.rs"), "{out}");
        assert!(out.contains("pub struct Engine"), "{out}");
        assert!(out.contains("impl Engine"), "{out}");
        assert!(out.contains("pub fn start"), "{out}");
        // Line numbers must be real: `pub struct Engine` is on line 3.
        assert!(
            out.lines()
                .any(|l| l.contains("3") && l.contains("pub struct Engine")),
            "expected a real line number for the struct:\n{out}"
        );
        // Non-source files still appear, so the model knows they exist.
        assert!(out.contains("README.md"), "{out}");
    }

